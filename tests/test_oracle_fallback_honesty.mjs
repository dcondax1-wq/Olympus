import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const app = await readFile(new URL('../tools/web_public/oracle/main.js', import.meta.url), 'utf8');
const page = await readFile(new URL('../tools/web_public/oracle/index.html', import.meta.url), 'utf8');
assert.match(app, /const canvas = document\.getElementById\('gl'\);\s*canvas\.hidden = true;\s*canvas\.setAttribute\('aria-hidden', 'true'\);/);
assert.match(app, /fallback\.setWorld\(w, mode\)/);
assert.match(page, /src="main\.js\?v=ofst2"/);
const source = await readFile(new URL('../tools/web_public/oracle/fallback.js', import.meta.url), 'utf8');
const { FallbackCity, beaconLevels } = await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const world = {levels:[{id:1,taken:false},{id:2,taken:true},{id:3,taken:false},{id:4,taken:false},{id:5,taken:false},{id:6,taken:false}]};
assert.equal(beaconLevels(world,'stale').length,0);
assert.deepEqual(beaconLevels(world,'live').map(x=>x.id),[1,3,4,5]);
assert.equal(beaconLevels(null,'site').length,0);
globalThis.devicePixelRatio = 1;
const labels = new Map();
const canvas = {clientWidth:390,clientHeight:844,getContext:()=>({setTransform(){}}),setAttribute:(k,v)=>labels.set(k,v)};
const fallback = new FallbackCity(canvas,true);
fallback.setWorld(world,'stale');
assert.equal(labels.get('role'),'img');
assert.match(labels.get('aria-label'),/last-seen snapshot/i);
assert.equal(fallback.mode,'stale');
fallback.setWorld(world,'demo');
assert.match(labels.get('aria-label'),/sample replay/i);
console.log('Oracle fallback stale and accessibility cases passed');
