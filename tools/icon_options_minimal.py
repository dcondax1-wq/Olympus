"""Minimal Home Screen icon options p1..p6 (owner 2026-10-30: "we went overboard on the logo"; the reference is his Planner
app icon: a charcoal tile, one flat grey glyph, a single white highlight with a soft glow). Writes
tools/web_public/icon_options/<p1..p6>/icon.svg; tools/icon_options_build.py p1 p2 ... renders the PNGs and
tools/icon_apply.py <key> switches the live icon.

    python tools/icon_options_minimal.py      # write the six SVGs
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OPT = os.path.join(ROOT, "tools", "web_public", "icon_options")

OPTIONS = {
    "p1": ("Dot Chart", "The Planner's dot grid on a charcoal card; a few dots rise into a price line and the last one is a glowing white square."),
    "p2": ("Reclaim", "A row of grey dots marks a level; a grey line dips below it and comes back above, the reclaim point glowing white."),
    "p3": ("Candles", "Four flat grey candles on a charcoal card, rising; the last candle is white with a soft glow."),
    "p4": ("One Candle", "A single bold grey candle outline centred on the tile, a glowing white core."),
    "p5": ("Pulse", "A thin grey line chart over a faint grid on a charcoal card, ending in one glowing white dot."),
    "p6": ("Level", "One grey horizontal level and a candle whose wick pierces it, the wick tip glowing white."),
}

GREY, GREY_HI, DOT, WHITE = "#8b8c91", "#c4c5ca", "#6f7075", "#f6f6f8"


def head(key, inner, card=True):
    name, line = OPTIONS[key]
    c = ('<rect x="176" y="196" width="672" height="640" rx="104" fill="url(#card)"/>'
         '<rect x="176" y="196" width="672" height="640" rx="104" fill="none" stroke="#ffffff" stroke-opacity="0.06" stroke-width="3"/>'
         if card else "")
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">
  <!-- Option {key.upper()} "{name}": {line} Full bleed, opaque. Generated by tools/icon_options_minimal.py, rendered by tools/icon_options_build.py. -->
<defs>
<linearGradient id="bg" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#2a2a2e"/><stop offset="0.55" stop-color="#151517"/><stop offset="1" stop-color="#0b0b0d"/></linearGradient>
<radialGradient id="sheen" cx="512" cy="120" r="620" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#ffffff" stop-opacity="0.10"/><stop offset="1" stop-color="#ffffff" stop-opacity="0"/></radialGradient>
<linearGradient id="card" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#3b3c40"/><stop offset="1" stop-color="#2a2b2e"/></linearGradient>
<filter id="glow" x="-150%" y="-150%" width="400%" height="400%"><feGaussianBlur stdDeviation="30"/></filter>
<filter id="glow2" x="-150%" y="-150%" width="400%" height="400%"><feGaussianBlur stdDeviation="12"/></filter>
</defs>
<rect width="1024" height="1024" fill="url(#bg)"/>
<rect width="1024" height="1024" fill="url(#sheen)"/>
<g id="art">
{c}
{inner}
</g>
</svg>
'''


def glow_sq(x, y, s, r):
    return (f'<rect x="{x - s}" y="{y - s}" width="{2 * s}" height="{2 * s}" rx="{r}" fill="#ffffff" opacity="0.55" filter="url(#glow)"/>'
            f'<rect x="{x - s}" y="{y - s}" width="{2 * s}" height="{2 * s}" rx="{r}" fill="#ffffff" opacity="0.6" filter="url(#glow2)"/>'
            f'<rect x="{x - s}" y="{y - s}" width="{2 * s}" height="{2 * s}" rx="{r}" fill="{WHITE}"/>')


def glow_dot(x, y, r):
    return (f'<circle cx="{x}" cy="{y}" r="{r * 2.2}" fill="#ffffff" opacity="0.45" filter="url(#glow)"/>'
            f'<circle cx="{x}" cy="{y}" r="{r * 1.2}" fill="#ffffff" opacity="0.6" filter="url(#glow2)"/>'
            f'<circle cx="{x}" cy="{y}" r="{r}" fill="{WHITE}"/>')


def p1():
    xs, ys = [292, 404, 516, 628, 740], [336, 448, 560, 672, 760]
    path = [(292, 672), (404, 560), (516, 616), (628, 448)]           # rising, one dip
    lit = set(path) | {(740, 336)}
    dots = "".join(f'<circle cx="{x}" cy="{y}" r="15" fill="{DOT}"/>' for y in ys[:-1] for x in xs if (x, y) not in lit)
    line = "M" + " L".join(f"{x} {y}" for x, y in path + [(740, 336)])
    on = "".join(f'<circle cx="{x}" cy="{y}" r="22" fill="{GREY_HI}"/>' for x, y in path)
    return head("p1", dots + f'<path d="{line}" fill="none" stroke="{GREY}" stroke-width="18" stroke-linecap="round" stroke-linejoin="round"/>'
                + on + glow_sq(740, 336, 34, 14))


def p2():
    level = "".join(f'<circle cx="{x}" cy="540" r="13" fill="{DOT}"/>' for x in range(268, 790, 58))
    line = "M252 400 C330 400 360 470 420 520 C470 560 500 668 560 668 C620 668 640 560 680 470 C710 405 740 380 772 372"
    return head("p2", level + f'<path d="{line}" fill="none" stroke="{GREY_HI}" stroke-width="26" stroke-linecap="round"/>'
                + glow_dot(772, 372, 34))


def candle(x, top, b0, b1, bot, w=64, color=GREY):
    return (f'<rect x="{x - 6}" y="{top}" width="12" height="{bot - top}" rx="6" fill="{color}"/>'
            f'<rect x="{x - w / 2}" y="{b0}" width="{w}" height="{b1 - b0}" rx="14" fill="{color}"/>')


def p3():
    cs = [(300, 560, 600, 700, 740), (420, 480, 520, 640, 690), (540, 430, 470, 580, 630)]
    body = "".join(candle(*c) for c in cs)
    last = (f'<rect x="628" y="300" width="96" height="300" rx="20" fill="#ffffff" opacity="0.5" filter="url(#glow)"/>'
            + candle(676, 290, 350, 540, 600, 64, WHITE))
    return head("p3", body + last)


def p4():
    return head("p4", '<rect x="501" y="196" width="22" height="632" rx="11" fill="' + GREY + '"/>'
                      '<rect x="372" y="330" width="280" height="364" rx="56" fill="#1a1a1d" stroke="' + GREY_HI + '" stroke-width="30"/>'
                      + glow_sq(512, 512, 52, 20), card=False)


def p5():
    grid = "".join(f'<line x1="232" y1="{y}" x2="792" y2="{y}" stroke="#ffffff" stroke-opacity="0.07" stroke-width="4"/>' for y in (380, 516, 652))
    line = "M244 690 L330 640 L400 668 L470 560 L540 600 L620 470 L690 500 L772 360"
    area = line + " L772 780 L244 780 Z"
    return head("p5", grid + f'<path d="{area}" fill="#ffffff" fill-opacity="0.05"/>'
                + f'<path d="{line}" fill="none" stroke="{GREY_HI}" stroke-width="22" stroke-linecap="round" stroke-linejoin="round"/>'
                + glow_dot(772, 360, 30))


def p6():
    lev = f'<rect x="196" y="500" width="632" height="18" rx="9" fill="{DOT}"/>'
    c = candle(512, 300, 560, 760, 800, 120, GREY_HI)
    tip = glow_dot(512, 300, 26)
    return head("p6", lev + c + tip, card=False)


def main():
    for key, fn in (("p1", p1), ("p2", p2), ("p3", p3), ("p4", p4), ("p5", p5), ("p6", p6)):
        d = os.path.join(OPT, key)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "icon.svg"), "w", encoding="utf-8") as fh:
            fh.write(fn())
        print("wrote", key, OPTIONS[key][0])


if __name__ == "__main__":
    main()
