"""research/writeups/INDEX.md: one table of every research write-up (front matter title, family, date, status, summary,
runs), newest first, grouped by verdict, plus the LIT notes in research/lit/*.md.

    python -X utf8 tools/writeups_index.py           # (re)write research/writeups/INDEX.md
    python -X utf8 tools/writeups_index.py --check   # exit 1 when INDEX.md is out of date (tests/test_writeups_index.py)
The dashboards skip INDEX.md in their write-up lists (engine/next_api.writeups, tools/build_web_dashboard._docs).
"""
from __future__ import annotations

import argparse
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WRITEUPS = os.path.join(ROOT, "research", "writeups")
LIT_DOCS = os.path.join(ROOT, "research", "lit")
OUT = os.path.join(WRITEUPS, "INDEX.md")
GROUPS = [("adopt-candidate", "Adopt-candidates (some are live now: see CLAUDE.md / STRATEGY.md)"), ("promising", "Promising leads"),
          ("finding", "Findings"), ("rejected", "Rejected"), ("info", "Reference / info")]


def front(text):
    meta = {}
    if text.startswith("---"):
        end = text.find("\n---", 3)
        if end > 0:
            for line in text[3:end].splitlines():
                if ":" in line:
                    k, v = line.split(":", 1)
                    meta[k.strip().lower()] = v.strip()
            text = text[end + 4:]
    if "title" not in meta:
        m = re.search(r"^#\s+(.+)$", text, re.M)
        meta["title"] = m.group(1).strip() if m else None
    return meta


def verdict(status):
    s = (status or "").lower()
    if s.startswith("rejected") or s.startswith("no adopt-candidate") and "promising" not in s:
        return "rejected"
    if "adopt-candidate" in s and not s.startswith("no adopt"):
        return "adopt-candidate"
    if "promising" in s:
        return "promising"
    if s.startswith("finding"):
        return "finding"
    return "info"


def _short(s, n=170):
    s = re.sub(r"\s+", " ", (s or "").replace("|", "/")).strip()
    return s if len(s) <= n else s[: n - 1].rsplit(" ", 1)[0] + "…"


def rows():
    out = []
    for p in sorted(glob.glob(os.path.join(WRITEUPS, "*.md"))):
        if os.path.basename(p).upper() == "INDEX.MD":
            continue
        m = front(open(p, encoding="utf-8").read())
        runs = [x.strip() for x in (m.get("runs") or "").strip("[]").split(",") if x.strip()]
        out.append({"file": os.path.basename(p), "title": m.get("title") or os.path.basename(p)[:-3], "family": m.get("family") or "-",
                    "date": m.get("date") or "-", "status": m.get("status") or "", "verdict": verdict(m.get("status")),
                    "summary": m.get("summary") or "", "runs": runs})
    return sorted(out, key=lambda r: (r["date"], r["file"]), reverse=True)


def render():
    R = rows()
    lit = sorted(glob.glob(os.path.join(LIT_DOCS, "*.md")))
    L = ["# Research write-ups: index", "",
         f"Generated by `tools/writeups_index.py`: {len(R)} write-ups, newest first in each group. Do not edit by hand; rerun the",
         "tool after adding a write-up. Every write-up's runs are in `research/runs/<id>.json` (Lab on both dashboards).", "",
         "| Group | Write-ups |", "|---|---:|"]
    L += [f"| [{lab}](#{g}) | {sum(1 for r in R if r['verdict'] == g)} |" for g, lab in GROUPS]
    for g, lab in GROUPS:
        G = [r for r in R if r["verdict"] == g]
        if not G:
            continue
        L += ["", f'<a id="{g}"></a>', f"## {lab}", "", "| Date | Write-up | Family | Verdict | Runs |", "|---|---|---|---|---:|"]
        for r in G:
            L.append(f"| {r['date']} | [{_short(r['title'], 90)}]({r['file']}) | {r['family']} | {_short(r['status'] or r['verdict'], 110)}<br>"
                     f"<sub>{_short(r['summary'])}</sub> | {len(r['runs'])} |")
    if lit:
        L += ["", "## LIT notes (research/lit)", ""]
        for p in lit:
            m = front(open(p, encoding="utf-8").read())
            L.append(f"- [{_short(m.get('title') or os.path.basename(p), 100)}](../lit/{os.path.basename(p)})")
    return "\n".join(L) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    txt = render()
    if a.check:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        ok = cur == txt
        print("INDEX.md up to date" if ok else "INDEX.md is out of date: python -X utf8 tools/writeups_index.py")
        return 0 if ok else 1
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(txt)
    print(f"{len(rows())} write-ups -> {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
