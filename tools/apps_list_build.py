"""Build the ONE shared OLYMPUS app list (tools/web_public/olympus/apps-list.js, window.OLYMPUS_APPS_LIST) from its two sources,
so it cannot drift:
  tools/web_public/jarvis/apps.js     BUILT_INS (id, name, group, accent, sub, glyph, live, url)  = the Jarvis switcher's list
  tools/web_public/olympus/olympus.js APPS (id -> name, glyph, colour)                           = the kit's table (loading veil, intros)
Each row: { id, name, glyph, colour, group, purpose, url, live }. glyph = BUILT_INS glyph, else the kit's, else the first letter.
The same bytes are written to web_next/js/next/apps-list.js (the PC dashboard has no olympus/ folder).
The Zenith launcher (tools/web_public/launcher.js, byte-identical in web_next/js/next/launcher.js) and, later, Jarvis read it.

    python tools/apps_list_build.py            write both files
    python tools/apps_list_build.py --check    exit 1 when a file is not what the sources give (tests/test_apps_list.py does the same)
"""
from __future__ import annotations

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.join(ROOT, "tools", "web_public")
OUT_PHONE = os.path.join(WEB, "olympus", "apps-list.js")
OUT_PC = os.path.join(ROOT, "web_next", "js", "next", "apps-list.js")


def read(*p):
    with open(os.path.join(*p), encoding="utf-8") as fh:
        return fh.read()


def js_str(m):
    """a JS string literal ('...' or "...") with \\uXXXX escapes -> the text"""
    q, body = m[0], m[1:-1]
    body = body.replace("\\'", "'").replace('\\"', '"')
    body = re.sub(r"\\u([0-9a-fA-F]{4})", lambda x: chr(int(x.group(1), 16)), body)
    return body.encode("utf-16", "surrogatepass").decode("utf-16")   # a surrogate pair (an emoji) becomes one character


STR = r"""'(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*\""""


def built_ins():
    src = read(WEB, "jarvis", "apps.js")
    block = re.search(r"export const BUILT_INS = Object\.freeze\(\[(.*?)\n\]\);", src, re.S).group(1)
    groups = {m.group(1): m.group(2).title() for m in re.finditer(r"Object\.freeze\(\{ id: '(\w+)', name: '(\w+)' \}\)", src)}
    rows = []
    for line in block.splitlines():
        m = re.match(r"\s*app\((" + STR + r"),\s*(" + STR + r"),\s*(" + STR + r"),\s*(" + STR + r"),\s*(" + STR + r")(?:,\s*(\{.*\}))?\),?\s*$", line)
        if not m:
            continue
        id_, name, group, accent, sub = (js_str(m.group(i)) for i in range(1, 6))
        more = m.group(6) or ""
        g = re.search(r"glyph:\s*(" + STR + ")", more)
        url = re.search(r"url:\s*(" + STR + ")", more)
        live = re.search(r"live:\s*(true|false)", more)
        rows.append(dict(id=id_, name=name, group=group, accent=accent, sub=sub, glyph=js_str(g.group(1)) if g else "",
                         url=(js_str(url.group(1)) if url else "../" + id_ + "/"), live=(live.group(1) == "true") if live else True))
    return rows, groups


def kit_table():
    src = read(WEB, "olympus", "olympus.js")
    block = re.search(r"var APPS = \{(.*?)\n  \};", src, re.S).group(1)
    out = {}
    for m in re.finditer(r"(\w+): \[(" + STR + r"),\s*(" + STR + r"),\s*(" + STR + r")\]", block):
        out[m.group(1)] = dict(name=js_str(m.group(2)), glyph=js_str(m.group(3)), colour=js_str(m.group(4)))
    return out


def build():
    rows, groups = built_ins()
    kit = kit_table()
    out = []
    for r in rows:
        k = kit.get(r["id"], {})
        glyph = r["glyph"] or k.get("glyph") or r["name"][:1].upper()
        # "../<id>/" in apps.js is relative to jarvis/; from the dashboard's root page it is "<id>/" ("" = the dashboard itself)
        path = re.sub(r"^\.\./", "", r["url"])
        out.append(dict(id=r["id"], name=r["name"], glyph=glyph, colour=r["accent"], group=r["group"], groupName=groups.get(r["group"], r["group"].title()),
                        purpose=r["sub"], path=path, live=r["live"]))
    return out


HEADER = """/* OLYMPUS app list (GENERATED by tools/apps_list_build.py from jarvis/apps.js BUILT_INS and olympus/olympus.js APPS: do not edit by hand,
 * tests/test_apps_list.py fails when this file and its sources disagree). One row per app:
 *   id, name, glyph, colour (its identity colour), group ('trading' | 'life' | 'money'), groupName, purpose (one plain line),
 *   path ('<id>/' from the site root, '' = the dashboard itself), live (true: it has a jarvis.json status card at <path>jarvis.json)
 * A plain script: window.OLYMPUS_APPS_LIST (frozen array); in node: module.exports. Used by the Zenith launcher; Jarvis can use it too. */
"""


def render(rows):
    body = ",\n".join("  " + json.dumps(r, ensure_ascii=True, separators=(", ", ": ")) for r in rows)
    return (HEADER + "(function (g) {\n  'use strict';\n  var rows = [\n" + body + "\n  ];\n"
            "  var list = Object.freeze(rows.map(function (r) { return Object.freeze(r); }));\n"
            "  g.OLYMPUS_APPS_LIST = list;\n  if (typeof module !== 'undefined' && module.exports) module.exports = list;\n"
            "}(typeof window !== 'undefined' ? window : globalThis));\n")


def main():
    text = render(build())
    if "--check" in sys.argv:
        bad = [p for p in (OUT_PHONE, OUT_PC) if not os.path.exists(p) or read(p) != text]
        print("apps-list: " + ("in step with its sources" if not bad else "OUT OF DATE: " + ", ".join(bad)))
        return 1 if bad else 0
    for p in (OUT_PHONE, OUT_PC):
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print("wrote", os.path.relpath(p, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
