def background(seed, stars=80, nebula=True):
    rnd = random.Random(seed)
    out = ['<g id="bg"><rect width="1024" height="1024" fill="url(#bg)"/>']
    if nebula:
        out.append(f'<ellipse cx="230" cy="800" rx="330" ry="200" fill="{TEAL}" opacity="0.13" filter="url(#b110)"/>')
        out.append(f'<ellipse cx="820" cy="210" rx="320" ry="220" fill="#7a5cff" opacity="0.2" filter="url(#b110)"/>')
        out.append(f'<ellipse cx="760" cy="860" rx="240" ry="140" fill="{GOLD}" opacity="0.06" filter="url(#b110)"/>')
    for _ in range(stars):
        x, y = rnd.uniform(10, 1014), rnd.uniform(10, 1014)
        r = rnd.choice((1.2, 1.6, 2.0, 2.6, 3.2))
        out.append(f'<circle cx="{f(x)}" cy="{f(y)}" r="{r}" fill="#dfe6ff" opacity="{rnd.uniform(0.18, 0.7):.2f}"/>')
    out.append("</g>")
    return "\n".join(out)


def svg(title, comment, defs, bg, art):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">\n'
            f'  <!-- {title}: {comment} Full bleed, opaque. Generated by tools/icon_options_detail.py, rendered by '
            f'tools/icon_options_build.py. -->\n<defs>{COMMON_DEFS}{defs}</defs>\n{bg}\n<g id="art">\n{art}\n</g>\n</svg>\n')


