C = 512
TEAL, INDIGO, GOLD = "#3ee0c8", "#6d7cff", "#f2c35b"


def f(v):
    return f"{v:.1f}".rstrip("0").rstrip(".")


def pt(r, deg, cx=C, cy=C):
    a = math.radians(deg)
    return cx + r * math.sin(a), cy - r * math.cos(a)


def P(*pts):
    return "M" + " L".join(f"{f(x)} {f(y)}" for x, y in pts) + " Z"


def blur(i, sd):
    return f'<filter id="{i}" x="-80%" y="-80%" width="260%" height="260%"><feGaussianBlur stdDeviation="{sd}"/></filter>'


