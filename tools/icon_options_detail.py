"""Write the detailed Compass (J1-J3) and Orbit (K1-K3) icon SVGs into tools/web_public/icon_options/<key>/icon.svg.

    python tools/icon_options_detail.py          # writes the 6 SVGs
    python tools/icon_options_build.py j1 j2 j3 k1 k2 k3   # renders them + redraws the sheets

The fine work (degree ticks, guilloché rosette, starfield, particle trail) is generated here so the SVGs stay exact;
each variant keeps one strong silhouette (the star / the candle + ring) so it still reads at 60 pt.
"""
