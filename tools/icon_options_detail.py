            f'<g clip-path="url(#dc)"><ellipse cx="420" cy="330" rx="{r * 0.95:.0f}" ry="{r * 0.55:.0f}" fill="url(#dome)" opacity="0.16" transform="rotate(-28 420 330)"/></g>'
