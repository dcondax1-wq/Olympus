def ticks(r_out, step=2, minor=10, mid=18, major=30, w=(2.2, 3.4, 5.5), gold_every=90, color="#c9d0ff"):
    out = []
    for i in range(0, 360, step):
        if i % gold_every == 0:
            ln, wd, col, op = major + 8, w[2] + 1, GOLD, 1
        elif i % 30 == 0:
            ln, wd, col, op = major, w[2], "#e6eaff", 0.95
        elif i % 10 == 0:
            ln, wd, col, op = mid, w[1], color, 0.8
        else:
            ln, wd, col, op = minor, w[0], color, 0.5
        (x1, y1), (x2, y2) = pt(r_out, i), pt(r_out - ln, i)
        out.append(f'<line x1="{f(x1)}" y1="{f(y1)}" x2="{f(x2)}" y2="{f(y2)}" stroke="{col}" stroke-width="{wd}" opacity="{op}"/>')
    return "\n".join(out)


def guilloche(r, n=36, rx=None, ry=None, color="#8f9bff", op=0.18, w=1.6):
    rx, ry = rx or r * 0.78, ry or r * 0.3
    return "\n".join(f'<ellipse cx="512" cy="512" rx="{f(rx)}" ry="{f(ry)}" fill="none" stroke="{color}" stroke-width="{w}" '
                     f'opacity="{op}" transform="rotate({f(i * 180 / n)} 512 512)"/>' for i in range(n))


def star(long_r, short_r, side=96, short_side=62, ridge=True, edge=True):
    out = []
    for a in (45, 135, 225, 315):   # short (indigo) points
        tip, l, r = pt(short_r, a), pt(short_side, a - 45), pt(short_side, a + 45)
        out.append(f'<path d="{P((C, C), tip, l)}" fill="#a9b3ff"/><path d="{P((C, C), tip, r)}" fill="#2c2a9a"/>')
        if edge:
            out.append(f'<path d="M{f(l[0])} {f(l[1])} L{f(tip[0])} {f(tip[1])} L{f(r[0])} {f(r[1])}" fill="none" stroke="#dfe3ff" stroke-opacity="0.55" stroke-width="2.5"/>')
    out.append(f'<g filter="url(#b24)" opacity="0.55"><path d="{P(*[pt(long_r if k % 2 == 0 else side, k * 45) for k in range(8)])}" fill="{GOLD}"/></g>')
    for a in (0, 90, 180, 270):
        tip, l, r = pt(long_r, a), pt(side, a - 45), pt(side, a + 45)
        lit, dark = ("goldL", "goldD") if a in (0, 270) else ("goldD", "goldL")
        out.append(f'<path d="{P((C, C), tip, l)}" fill="url(#{lit})"/><path d="{P((C, C), tip, r)}" fill="url(#{dark})"/>')
        if ridge:
            out.append(f'<line x1="512" y1="512" x2="{f(tip[0])}" y2="{f(tip[1])}" stroke="#fffaf0" stroke-width="3" opacity="0.8"/>')
        if edge:
            out.append(f'<path d="M{f(l[0])} {f(l[1])} L{f(tip[0])} {f(tip[1])} L{f(r[0])} {f(r[1])}" fill="none" stroke="#fff3cf" stroke-opacity="0.7" stroke-width="2.5" stroke-linejoin="round"/>')
    return "\n".join(out)


def hub(r=62, ring=True):
    out = [f'<circle cx="512" cy="512" r="{r + 34}" fill="{TEAL}" opacity="0.55" filter="url(#b24)"/>']
    if ring:
        out.append(f'<circle cx="512" cy="512" r="{r + 14}" fill="#0b0c1e" stroke="url(#goldRing)" stroke-width="9"/>')
        out += [f'<line x1="{f(pt(r + 10, a)[0])}" y1="{f(pt(r + 10, a)[1])}" x2="{f(pt(r + 3, a)[0])}" y2="{f(pt(r + 3, a)[1])}" stroke="{GOLD}" stroke-width="2.5"/>' for a in range(0, 360, 15)]
    out.append(f'<circle cx="512" cy="512" r="{r}" fill="url(#gem)"/>')
    # brilliant-cut facets on the gem
    out += [f'<line x1="512" y1="512" x2="{f(pt(r, a)[0])}" y2="{f(pt(r, a)[1])}" stroke="#e6fffa" stroke-opacity="0.35" stroke-width="2"/>' for a in range(0, 360, 45)]
    out.append(f'<circle cx="512" cy="512" r="{r * 0.5:.0f}" fill="none" stroke="#e6fffa" stroke-opacity="0.4" stroke-width="2"/>')
    out.append(f'<ellipse cx="{512 - r * 0.32:.0f}" cy="{512 - r * 0.36:.0f}" rx="{r * 0.28:.0f}" ry="{r * 0.18:.0f}" fill="#ffffff" opacity="0.95" transform="rotate(-35 {512 - r * 0.32:.0f} {512 - r * 0.36:.0f})"/>')
    return "\n".join(out)


