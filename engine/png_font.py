_NARROW = set(".,:;!'|·")              # punctuation: 3 columns wide (cols 1-3), so "25,560.25" reads tight
_SUBST = {"−": "-", "–": "-", "—": "-", "≥": ">", "≤": "<", "→": ">", "…": "...",
          "•": "·", "×": "X", "’": "'", "‘": "'", "“": "'", "”": "'", '"': "'"}
H = 7


def _bits(s: str) -> np.ndarray:
    return np.array([[c == "1" for c in row] for row in s.split()], dtype=np.float32)


GLYPHS = {k: (_bits(v)[:, 1:4] if k in _NARROW else _bits(v)) for k, v in _G.items()}


def norm(text) -> str:
    out = []
    for ch in str(text or ""):
        ch = _SUBST.get(ch, ch)
        out.append(ch.upper())
    return "".join(out)


def mask(text) -> np.ndarray:
    """(7, width) float32 coverage for one line at scale 1 (1 px gap between letters)."""
    gs = [GLYPHS.get(ch) if ch in GLYPHS else GLYPHS["?"] for ch in norm(text)]
    if not gs:
        return np.zeros((H, 0), np.float32)
    cols = []
    for g in gs:
        cols.append(g)
        cols.append(np.zeros((H, 1), np.float32))
    return np.concatenate(cols[:-1], axis=1)


def width(text, scale: int = 1) -> int:
    n = norm(text)
    if not n:
        return 0
    return (sum((GLYPHS.get(ch, GLYPHS["?"]).shape[1]) for ch in n) + len(n) - 1) * int(scale)


def fit(text, max_px: int, scale: int = 1) -> str:
    """The text cut (with '...') so it fits in max_px at this scale."""
    t = norm(text)
    if width(t, scale) <= max_px:
        return t
    while t and width(t + "...", scale) > max_px:
        t = t[:-1]
    return t.rstrip() + "..."
